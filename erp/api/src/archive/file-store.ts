import { promises as fs } from 'fs';
import * as path from 'path';

/**
 * Archive files live on disk under ARCHIVE_DIR (a folder on the server, or a network share that is
 * backed up), not in SQL Server, so scans do not eat into the 10 GB Express limit.
 */
export class FileStore {
  private readonly root: string;

  constructor(dir: string) {
    this.root = path.resolve(dir);
  }

  async put(key: string, data: Buffer) {
    const file = this.resolve(key);
    await fs.mkdir(path.dirname(file), { recursive: true });
    // wx: never overwrite an archived file
    await fs.writeFile(file, data, { flag: 'wx' });
  }

  async get(key: string): Promise<Buffer | null> {
    try {
      return await fs.readFile(this.resolve(key));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw err;
    }
  }

  async remove(key: string) {
    await fs.rm(this.resolve(key), { force: true });
  }

  /** Keys are generated by the API, but never let one escape the archive folder */
  private resolve(key: string) {
    const file = path.resolve(this.root, key);
    if (!file.startsWith(this.root + path.sep)) throw new Error(`Invalid archive key: ${key}`);
    return file;
  }
}
