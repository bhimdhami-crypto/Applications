import { PrismaClient } from '@prisma/client';
import { promises as fs } from 'fs';
import * as path from 'path';

/** Where uploaded files live. Shared by the API and the seed and import scripts. */
export interface FileStore {
  put(key: string, data: Buffer | string): Promise<void>;
  putMany(files: Array<[key: string, data: Buffer | string]>): Promise<void>;
  get(key: string): Promise<Buffer | null>;
  remove(key: string): Promise<void>;
}

/**
 * STORAGE_DRIVER=database keeps files in the StoredFile table, for hosts with no lasting disk (Vercel).
 * Otherwise files go on the local disk under STORAGE_DIR.
 */
export function createFileStore(prisma: PrismaClient, env: Record<string, string | undefined> = process.env): FileStore {
  return env.STORAGE_DRIVER === 'database' ? new DatabaseStore(prisma) : new DiskStore(env.STORAGE_DIR ?? 'storage');
}

class DiskStore implements FileStore {
  private readonly root: string;

  constructor(dir: string) {
    this.root = path.resolve(dir);
  }

  async put(key: string, data: Buffer | string) {
    const file = this.resolve(key);
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, data);
  }

  async putMany(files: Array<[string, Buffer | string]>) {
    for (const [key, data] of files) await this.put(key, data);
  }

  async get(key: string): Promise<Buffer | null> {
    try {
      return await fs.readFile(this.resolve(key));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw err;
    }
  }

  async remove(key: string) {
    await fs.rm(this.resolve(key), { force: true });
  }

  /** Keys are generated by the API, but never let one escape the storage folder. */
  private resolve(key: string) {
    const file = path.resolve(this.root, key);
    if (!file.startsWith(this.root + path.sep)) throw new Error(`Invalid storage key: ${key}`);
    return file;
  }
}

class DatabaseStore implements FileStore {
  constructor(private readonly prisma: PrismaClient) {}

  async put(key: string, data: Buffer | string) {
    const bytes = toBytes(data);
    await this.prisma.storedFile.upsert({ where: { key }, create: { key, data: bytes }, update: { data: bytes } });
  }

  async putMany(files: Array<[string, Buffer | string]>) {
    for (let i = 0; i < files.length; i += 500) {
      const data = files.slice(i, i + 500).map(([key, d]) => ({ key, data: toBytes(d) }));
      await this.prisma.storedFile.createMany({ data, skipDuplicates: true });
    }
  }

  async get(key: string): Promise<Buffer | null> {
    const row = await this.prisma.storedFile.findUnique({ where: { key } });
    return row ? Buffer.from(row.data) : null;
  }

  async remove(key: string) {
    await this.prisma.storedFile.deleteMany({ where: { key } });
  }
}

const toBytes = (data: Buffer | string) => new Uint8Array(typeof data === 'string' ? Buffer.from(data) : data);
